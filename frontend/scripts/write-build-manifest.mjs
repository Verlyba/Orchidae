/**
 * Records WHICH sources produced the committed bundle in ../web.
 *
 * The built output is committed so that someone with Python but no Node can
 * run Orchiday straight after cloning. That only works if the bundle is
 * actually kept in sync, and "is the build stale?" cannot be answered from
 * file timestamps: git does not preserve mtimes, so on a fresh clone every
 * file looks equally old. A content hash does answer it, on any machine, in
 * any order. scripts/verify.sh recomputes it and fails when it differs.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, '..');
const web = path.resolve(frontend, '..', 'web');

export function hashSources(frontendDir) {
  const files = [];
  const walk = dir => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
      if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p); else files.push(p);
    }
  };
  walk(path.join(frontendDir, 'src'));
  walk(path.join(frontendDir, 'public'));
  for (const f of ['index.html', 'vite.config.ts', 'tsconfig.json', 'package.json']) {
    files.push(path.join(frontendDir, f));
  }

  const h = crypto.createHash('sha256');
  for (const f of files.sort()) {
    h.update(path.relative(frontendDir, f).split(path.sep).join('/'));
    h.update('\0');
    h.update(fs.readFileSync(f));
    h.update('\0');
  }
  return { hash: h.digest('hex'), count: files.length };
}

// Only write the manifest when run as a script; verify.sh imports hashSources.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { hash, count } = hashSources(frontend);
  const manifest = {
    _comment: 'Generated by frontend/scripts/write-build-manifest.mjs. Do not edit. '
      + 'Rebuild with: cd frontend && npm run build',
    sourceHash: hash,
    sourceFiles: count,
  };
  fs.writeFileSync(path.join(web, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log(`build-manifest.json written (${count} source files, ${hash.slice(0, 12)}…)`);
}
